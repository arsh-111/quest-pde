"""Generate results/RESULTS.md (the numeric tables the README links to) from result JSON files only."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"
ld = lambda n: json.loads((R / n).read_text())  # noqa: E731
ev, sv, dv = ld("eval_metrics.json"), ld("solver_validation.json")["summary"], ld("derived_outputs.json")
pc, dev = ld("padding_choice.json"), ld("device_benchmark.json")
p = lambda v: f"{100 * v:.3f}%"  # noqa: E731
L = ["# Results (generated by scripts/make_report.py from results/*.json; do not edit by hand)", ""]

L += ["## Solver validation (20 held-out samples, keys 3600-3619, 1024 cells x 101 times)", "",
      "| solver | rel L2 vs tight BDF (mean / max) | rel L2 vs PDEBench data (mean) | seconds per run |", "|---|---|---|---|"]
for dt in ["2.0", "1.0", "0.5", "0.25"]:
    s = sv[f"implicit_dt{dt}"]
    L.append(f"| implicit BDF2, dt={dt} | {s['vs_tight_ref_mean']:.1e} / {s['vs_tight_ref_max']:.1e} | {p(s['vs_data_mean'])} "
             f"| {s['seconds_mean_1024cells_101outputs']:.2f} |")
b = sv["tight_bdf_vs_data"]
L += ["", f"Tight BDF (rtol 1e-8) vs data: mean {p(b['mean'])} (min {p(b['min'])}, max {p(b['max'])}): the dataset's own "
      "RK45 tolerance error. By time: " + ", ".join(f"{k} {p(v)}" for k, v in sv["dataset_error_by_t_mean"].items()), ""]

L += ["## In-distribution test (400 samples, keys 3600-3999, 256 points, t = 5..500)", "",
      "| model | vs dataset: mean | median | p95 | worst | vs accurate solver: mean | mass error (rel) |", "|---|---|---|---|---|---|---|"]
for n, r in ev["test"].items():
    d = r["rel_l2_vs_data"]
    L.append(f"| {n} | {p(d['mean'])} | {p(d['median'])} | {p(d['p95'])} | {p(d['worst'])} | "
             f"{p(r['rel_l2_vs_solver']['mean'])} | {r['mass']['mean_rel_abs_mass_error']:.1e} |")
f = ev["data_vs_solver_on_test"]
L += ["", f"Dataset vs accurate solver on the same 400 samples: mean {p(f['mean'])} (worst {p(f['worst'])}).",
      f"Ensemble members: {', '.join(ev['meta']['ensemble_members'])} (padding chosen by validation: {pc['chosen']}; "
      f"val pad0 {pc['val_pad0']:.3e}, pad25 {pc['val_pad25']:.3e}).", ""]

L += ["### Boundary vs interior (absolute error, test, vs dataset)", "",
      "| model | left 4 pts MAE | interior MAE | right 4 pts MAE | last point MAE | mean u at last point |", "|---|---|---|---|---|---|"]
for n, r in ev["test"].items():
    bd = r["boundary"]
    L.append(f"| {n} | {bd['left_mae']:.1e} | {bd['interior_mae']:.1e} | {bd['right_mae']:.1e} | {bd['last_point_mae']:.1e} "
             f"| {bd['last_point_mean_abs_u']:.1e} |")
L += ["", "Error vs time (mean rel L2 over x, vs dataset): "]
for n, r in ev["error_vs_t_at"].items():
    L.append(f"- {n}: " + ", ".join(f"{k} {p(v)}" for k, v in r.items()))
L.append("")

L += ["## Out of distribution (46 solver-generated trajectories; truth = accurate solver)", "",
      "Mean rel L2 per IC family (const_in = in-distribution control generated by the solver):", ""]
cats = list(next(iter(ev["ood"].values())).keys())
L += ["| model | " + " | ".join(cats) + " |", "|---" * (len(cats) + 1) + "|"]
for n, r in ev["ood"].items():
    L.append(f"| {n} | " + " | ".join(p(r[c]["mean"]) for c in cats) + " |")
L.append("")

L += ["## Resolution transfer (100 test samples; trained at 256 points)", "", "| model | rel L2 at 256 | rel L2 at 1024 (zero-shot) |", "|---|---|---|"]
for n, r in ev["resolution_transfer"].items():
    L.append(f"| {n} | {p(r['rel_l2_at_256_same_samples']['mean'])} | {p(r['rel_l2_at_1024']['mean'])} |")
L.append("")

ib = ev["ic_vs_bc"]
L += ["## IC vs boundary influence (accurate solver)", "",
      f"- trajectory change, IC level 0.1 -> 0.2: {p(ib['rel_change_ic_0.1_to_0.2'])}",
      f"- trajectory change, IC level 0.0 -> 0.2 (full training range): {p(ib['rel_change_ic_0.0_to_0.2_full_range'])}",
      f"- trajectory change, boundary value 1.0 -> 1.1: {p(ib['rel_change_bc_1.0_to_1.1'])}",
      "- full-range IC effect by time: " + ", ".join(f"{k} {p(v)}" for k, v in ib["ic_full_range_by_t"].items()),
      f"- IC-blind mean-trajectory baseline on test: {p(ib['mean_trajectory_baseline_test_rel_l2'])}", ""]

pr = ev["pde_residual_rms"]
L += ["## PDE residual (RMS of du/dt - D/R(u) u_xx on interior points)", "", "| field | test | OOD |", "|---|---|---|",
      f"| ground truth | {pr['ground_truth_test']['mean']:.2e} | {pr['ground_truth_ood']['mean']:.2e} |"]
for n in ev["test"]:
    L.append(f"| {n} | {pr[n + '_test']['mean']:.2e} | {pr[n + '_ood']['mean']:.2e} |")
L += ["", "Note: test ground truth is the dataset (RK45 noise inflates its residual); OOD ground truth is the accurate solver.", ""]

tr = ev["trust"]
L += ["## Trust signals (Spearman rank correlation with the ensemble-mean error)", "", "| signal | test | OOD | pooled |", "|---|---|---|---|"]
for sig in ["spread", "residual"]:
    L.append(f"| {sig} | " + " | ".join(f"{tr[f'{sig}_vs_error_{k}']['rho']:.2f} (p={tr[f'{sig}_vs_error_{k}']['p']:.1e})"
                                         for k in ["test", "ood", "pooled"]) + " |")
L += ["", f"Spread threshold (99th pct of test spread): {tr['spread_threshold_p99_test']:.2e}; OOD flagged fraction by family: "
      + ", ".join(f"{k} {v:.0%}" for k, v in tr["ood_flagged_fraction_by_category"].items()), ""]

L += ["## Derived outputs (test, 400 samples)", "",
      "| output | sensitivity to c (std/mean) | ensemble vs data | ensemble vs solver | data vs solver | interp-c vs data |", "|---|---|---|---|---|---|"]
for k, r in dv["outputs"].items():
    L.append(f"| {k} | {r['sensitivity_to_c_std_over_mean']:.3f} | {p(r['ensemble_vs_data_rel_l2'])} | "
             f"{p(r['ensemble_vs_solver_rel_l2'])} | {p(r['data_vs_solver_rel_l2'])} | {p(r['interp_c_vs_data_rel_l2'])} |")
L += ["", "Dataset lookup table (interpolating K stored trajectories in c) vs held-out data: "
      + ", ".join(f"K={k}: {p(v['mean_rel_l2_vs_data'])} ({v['size_mb_float32']} MB)" for k, v in dv["dataset_lookup_table"].items()), ""]

sw = sorted((R / "train").glob("sweep_*.json"), key=lambda q: json.loads(q.read_text())["config"]["n_train"])
if sw:
    L += ["## Data efficiency (FNO, seed 0, 6000 optimiser steps for every size; validation set, 400 samples)", "",
          "| n_train | best val rel L2 | train seconds |", "|---|---|---|"]
    for q in sw:
        c = json.loads(q.read_text())["config"]
        L.append(f"| {c['n_train']} | {p(c['best_val_rel_l2'])} | {c['train_seconds']} |")
    L.append("")

L += ["## CPU timing (4 threads)", "", "| what | seconds |", "|---|---|"]
for n, r in ev["timing_cpu"].items():
    for k, v in r.items():
        L.append(f"| {n} {k} | {v:.4f} |")
L += ["", "## Training device benchmark (seconds per epoch, 3200 samples, batch 32)", ""]
L += [f"- {k}: {v['sec_per_epoch']} s" for k, v in dev.items() if isinstance(v, dict)]
(R / "RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("\n".join(L))
